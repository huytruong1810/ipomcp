"""IPF qualification: particle beliefs versus exact beliefs along the same histories.

For a Tiger agent at level 2 or 3, two banks with the same seed and the same
modeled-opponent planners are built: one with exact enumeration, one with the
interactive particle filter at N particles. Both condition on the same history
of the agent's own actions and observations. After every step this records, for
the agent's belief:

- ``level_tv``: total variation between the posteriors over the opponent's level;
- ``physical_error``: |P_ipf(tiger left) - P_exact(tiger left)|;
- ``nested_tv``: total variation between the joint masses of nested model paths
  at nesting depth 2 (what the agent believes the opponent believes about its
  own level), the quantity a sunburst displays.

Histories are generated by the environment with the agent listening except for
one opening, and a uniform-random opponent, so every observation is supported.
The gate for using the IPF at scale is that these errors shrink as N grows.
The worst case matters as much as the mean: a nested particle belief can flip
a modeled opponent's greedy action, a discrete error that more particles make
rarer but not smaller, so the summary reports the maximum and the share of
steps with level TV above 0.2. A few histories understate it; the default is 12.
"""

import argparse
import itertools
import json
import math
import random
from pathlib import Path

import pandas as pd

from ipomdp.analysis.hierarchy import hierarchy_error, level_posterior, nested_hierarchy
from ipomdp.domains.tiger import TIGER_LEFT, TigerModel
from ipomdp.experiments.bootstrapper import HierarchyBuilder
from ipomdp.experiments.oracle import HISTORY_ACTIONS, sample_history
from ipomdp.planning.config import PlannerConfig
from ipomdp.planning.solver_bank import SolverBank

NESTED = {3: {2: 0.1, 1: 0.8, 0: 0.1}, 2: {1: 0.5, 0: 0.5}, 1: {0: 1.0}}


def total_variation(a, b):
    return 0.5 * math.fsum(abs(a.get(k, 0.0) - b.get(k, 0.0)) for k in set(a) | set(b))


def left(belief):
    return math.fsum(w for atom, w in belief.mass if atom.state == TIGER_LEFT)


def evaluate(level, particles, history_seed, modeled_simulations=50, depth=2):
    physics = TigerModel()
    config = PlannerConfig(
        simulations=modeled_simulations, depth=depth, modeled_simulations=modeled_simulations
    )

    def agent(bank):
        return HierarchyBuilder(bank).build(
            "i",
            level,
            physics,
            "j",
            config=config,
            level_weights=NESTED[level],
            nested_level_weights=NESTED,
        )

    exact = agent(SolverBank(history_seed))
    approximate = agent(SolverBank(history_seed, particles=particles))
    history = sample_history(
        physics, len(HISTORY_ACTIONS), random.Random(f"history/{history_seed}")
    )
    rows = []
    for step, (action, observation) in enumerate(history, 1):
        exact.update_root(action, observation)
        approximate.update_root(action, observation)
        rows.append(
            dict(
                level=level,
                particles=particles,
                history=history_seed,
                step=step,
                level_tv=total_variation(
                    level_posterior(exact.belief), level_posterior(approximate.belief)
                ),
                physical_error=abs(left(exact.belief) - left(approximate.belief)),
                nested_tv=hierarchy_error(
                    nested_hierarchy(approximate.belief, "i", level, depth=2),
                    nested_hierarchy(exact.belief, "i", level, depth=2),
                )[2]["mass_tv"],
                exact_support=len(exact.belief.mass),
                particle_support=len(approximate.belief.mass),
            )
        )
    return rows


def summarize(rows):
    frame = pd.DataFrame(rows)
    return (
        frame.groupby(["level", "particles"])
        .agg(
            n=("level_tv", "size"),
            level_tv=("level_tv", "mean"),
            physical_error=("physical_error", "mean"),
            nested_tv=("nested_tv", "mean"),
            max_level_tv=("level_tv", "max"),
            share_above_0_2=("level_tv", lambda tv: (tv > 0.2).mean()),
            exact_support=("exact_support", "max"),
        )
        .reset_index()
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--levels", type=int, nargs="+", default=[2, 3])
    parser.add_argument("--particles", type=int, nargs="+", default=[16, 64, 256, 1024])
    parser.add_argument("--histories", type=int, default=12)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=False)
    rows = [
        row
        for level, particles, history in itertools.product(
            args.levels, args.particles, range(args.histories)
        )
        for row in evaluate(level, particles, history)
    ]
    (args.output / "rows.json").write_text(json.dumps(rows))
    summary = summarize(rows)
    summary.to_csv(args.output / "summary.csv", index=False)
    print(summary.round(4).to_string(index=False))


if __name__ == "__main__":
    main()
